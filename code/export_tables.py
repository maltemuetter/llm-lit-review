"""Export the supplementary domain and rate tables to LaTeX files.

Generated from the screening results, so the supplementary tables cannot drift
from the analysis.
"""

import collections
import statistics
from pathlib import Path

from analyse_screening import (MODELS, PROMPTS, all_configurations, domain_weights,
                               final_sample_pmids, gated_papers_per_year, load_successful,
                               weights_for)

SUPPLEMENTARY_DIR = Path(__file__).parent.parent.parent / "supplementary"
DOMAIN_TABLE_PATH = SUPPLEMENTARY_DIR / "table_domains.tex"
RATES_TABLE_PATH = SUPPLEMENTARY_DIR / "table_rates.tex"
GENERATED_NOTE = "% Generated by code/export_tables.py -- do not edit by hand."
MODEL_LABELS = {"mistral-large-2512": "Mistral", "claude-sonnet-5": "Sonnet"}
REFUSING_MODEL = "claude-sonnet-5"
NARROW_COLUMN_GAP_LABELS = {"tab:domains"}
NARROW_COLUMN_GAP = "\\setlength{\\tabcolsep}{2.5pt}"
DOMAIN_LABELS = {
    "antimicrobial": "Antimicrobial",
    "oncology": "Oncology",
    "other_therapeutic": "Other therapeutic use",
    "environmental_agricultural": "Environmental or agricultural",
    "not_a_drug_combination": "Not a drug combination",
}
DOMAIN_HEADER_CELLS = [
    ("", "Domain"),
    ("Consensus call", "(both models)"),
    ("Single call", "(one model)"),
    ("Split call", "(models differ)"),
    ("Weighted", "papers"),
    ("Domain", "share $s_d$"),
    ("Yes-rate $r_{d,c}$ (\\%)", "range (median)"),
    ("Sonnet cells", "missing"),
]
DOMAIN_CAPTION = ("Domain classification of the screening sample and outcome rates by domain. "
                  "A paper counts fully towards a domain on a consensus or single call and half on "
                  "a split call, so split calls appear in two rows (the total counts papers). The "
                  "domain share $s_d$ = weighted papers/1,000 enters \\autoref{eq:extrapolation}. "
                  "Yes-rate $r_{d,c}$: range across the ten configurations, with the median in "
                  "parentheses; the total row gives the rate across all domains. Sonnet cells "
                  "missing: outcome cells without an answer from Claude Sonnet, counted with the "
                  "same domain weights.")
RATES_HEADER = r"Model & Prompt & Yes/answered & Rate & Papers/year (extrapolated) \\"


def screening_data():
    """Load the domain and outcome cells and the analysed sample pmids."""
    domain_cells = load_successful("domain")
    outcome_cells = load_successful("outcome")
    answered = {key[0] for key in domain_cells} | {key[0] for key in outcome_cells}
    return domain_cells, outcome_cells, sorted(final_sample_pmids() & answered)


def latex_table(caption, label, column_spec, header, body_lines):
    """Assemble a LaTeX table environment from its parts."""
    column_gap = [f"  {NARROW_COLUMN_GAP}"] if label in NARROW_COLUMN_GAP_LABELS else []
    return "\n".join([GENERATED_NOTE, "\\begin{table}[h]", "  \\centering\\small", *column_gap,
                      f"  \\caption{{{caption}}}", f"  \\label{{{label}}}",
                      f"  \\begin{{tabular}}{{{column_spec}}}", "    \\hline", f"    {header}",
                      "    \\hline", *body_lines, "    \\hline", "  \\end{tabular}",
                      "\\end{table}", ""])


def domain_vote_counts(domain_cells, pmids):
    """Count agreed, single-model and split domain votes per domain."""
    agreed, single, split = collections.Counter(), collections.Counter(), collections.Counter()
    for pmid in pmids:
        votes = [domain_cells.get((pmid, model, "domain"), {}).get("domain") for model in MODELS]
        votes = [vote for vote in votes if vote]
        if len(votes) == 1:
            single[votes[0]] += 1
        elif len(votes) == 2:
            (agreed if votes[0] == votes[1] else split).update(set(votes))
    return agreed, single, split


def missing_outcome_cells(outcome_cells, pmids, domain_weights_by_pmid):
    """Weight the refusing model's missing and possible outcome cells by domain."""
    missing, possible = collections.Counter(), collections.Counter()
    for pmid in pmids:
        missed = sum((pmid, REFUSING_MODEL, prompt) not in outcome_cells for prompt in PROMPTS)
        for domain, weight in domain_weights_by_pmid[pmid].items():
            missing[domain] += weight * missed
            possible[domain] += weight * len(PROMPTS)
    return missing, possible


def rate_summary_text(rows):
    """Format the rate range across configurations with its median."""
    rates = [100 * row["rate"] for row in rows]
    return f"{min(rates):.1f}--{max(rates):.1f} ({statistics.median(rates):.1f})"


def missing_text(missing, possible):
    """Format missing out of possible cells."""
    return f"{missing:,g}/{possible:,g}"


def header_line(cells):
    """Render two-line column headers as one LaTeX table row."""
    stacked = [f"\\begin{{tabular}}[b]{{@{{}}c@{{}}}}{top}\\\\{bottom}\\end{{tabular}}"
               if top else bottom for top, bottom in cells]
    return " & ".join(stacked) + " \\\\"


def table_row(cells):
    """Join cell values into one LaTeX table row."""
    return "    " + " & ".join(str(cell) for cell in cells) + " \\\\"


class DomainTally:
    """Domain classification tallies of the screening sample."""

    def __init__(self, domain_cells, outcome_cells, pmids):
        self.outcome_cells, self.pmids = outcome_cells, pmids
        self.weights = domain_weights(domain_cells, pmids)
        self.agreed, self.single, self.split = domain_vote_counts(domain_cells, pmids)
        self.missing, self.possible = missing_outcome_cells(outcome_cells, pmids, self.weights)

    def row(self, domain, label):
        """Render one domain as a LaTeX table row."""
        weighted_n = self.agreed[domain] + self.single[domain] + self.split[domain] / 2
        rows = all_configurations(self.outcome_cells, self.pmids, weights_for(self.weights, domain))
        return table_row([label, self.agreed[domain], self.single[domain], self.split[domain],
                          f"{weighted_n:g}", f"{weighted_n / len(self.pmids):.3f}",
                          rate_summary_text(rows),
                          missing_text(self.missing[domain], self.possible[domain])])

    def total_row(self):
        """Render the totals across domains as a LaTeX table row."""
        rows = all_configurations(self.outcome_cells, self.pmids)
        return table_row(["Total", sum(self.agreed.values()), sum(self.single.values()),
                          sum(self.split.values()) // 2, f"{len(self.pmids):,}", "1.000",
                          rate_summary_text(rows),
                          missing_text(sum(self.missing.values()), sum(self.possible.values()))])

    def lines(self):
        """Render all domain rows followed by the total row."""
        domain_rows = [self.row(domain, label) for domain, label in DOMAIN_LABELS.items()]
        return domain_rows + ["    \\hline", self.total_row()]


def rate_line(row, mean_per_year):
    """Render one configuration as a LaTeX table row."""
    prompt = row["prompt"].split("_")[0]
    counts = f"{row['yes']:,.0f}/{row['n']:,.0f}"
    return (f"    {MODEL_LABELS[row['model']]} & {prompt} & {counts} & "
            f"{100 * row['rate']:.1f}\\% & {mean_per_year * row['rate']:,.0f} \\\\")


def summary_lines(rows, mean_per_year):
    """Render the median and range across configurations as table rows."""
    rates = [row["rate"] for row in rows]
    median = statistics.median(rates)
    low, high = min(rates), max(rates)
    return ["    \\hline",
            f"    Median & & & {100 * median:.1f}\\% & {mean_per_year * median:,.0f} \\\\",
            f"    Range & & & {100 * low:.1f}--{100 * high:.1f}\\% & "
            f"{mean_per_year * low:,.0f}--{mean_per_year * high:,.0f} \\\\"]


def rates_caption(rows, per_year):
    """Build the rate-table caption from the counts and interval widths."""
    total, years = sum(per_year.values()), len(per_year)
    widest_margin = max(max(row["rate"] - row["low"], row["high"] - row["rate"]) for row in rows)
    return ("Percentage of papers in the screening sample presenting synergy as desirable "
            "(i.e.\\ answered `yes') for each configuration, and the resulting estimated number "
            "of eligible papers per year across all domains. Rates are scaled to the mean number "
            f"of eligible papers per year: {total:,} papers over {years} years (2010--2025), "
            f"i.e.\\ $\\bar{{N}}$ = {total / years:,.0f}. Each rate carries a sampling "
            f"uncertainty of up to $\\pm${100 * widest_margin:.0f} percentage points "
            "(95\\% confidence interval, normal approximation).")


def build_rates_table(outcome_cells, pmids, per_year):
    """Assemble the rate table source."""
    rows = sorted(all_configurations(outcome_cells, pmids), key=lambda row: row["rate"])
    mean_per_year = sum(per_year.values()) / len(per_year)
    body = [rate_line(row, mean_per_year) for row in rows] + summary_lines(rows, mean_per_year)
    return latex_table(rates_caption(rows, per_year), "tab:rates", "llrrr", RATES_HEADER, body)


def main():
    """Write both generated tables into the supplementary folder."""
    domain_cells, outcome_cells, pmids = screening_data()
    tally = DomainTally(domain_cells, outcome_cells, pmids)
    DOMAIN_TABLE_PATH.write_text(latex_table(DOMAIN_CAPTION, "tab:domains", "lrrrrrrr",
                                             header_line(DOMAIN_HEADER_CELLS), tally.lines()))
    RATES_TABLE_PATH.write_text(build_rates_table(outcome_cells, pmids, gated_papers_per_year()))
    print(f"wrote {DOMAIN_TABLE_PATH} and {RATES_TABLE_PATH}")


if __name__ == "__main__":
    main()
