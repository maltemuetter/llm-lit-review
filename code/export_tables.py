"""Export the per-configuration rate table to a LaTeX file.

Generated from the screening results, so the supplementary table cannot drift
from the analysis.
"""

from pathlib import Path

from analyse_screening import (all_configurations, final_sample_pmids, gated_papers_per_year,
                               load_successful)

SUPPLEMENTARY_DIR = Path(__file__).parent.parent.parent / "supplementary"
TABLE_PATH = SUPPLEMENTARY_DIR / "table_rates.tex"
GENERATED_NOTE = "% Generated by code/export_rates_table.py -- do not edit by hand."
MODEL_LABELS = {"mistral-large-2512": "Mistral", "claude-sonnet-5": "Sonnet"}
COLUMN_HEADER = (r"Model & Prompt & Yes/answered & Rate (95\% CI) "
                 r"& Papers per year (95\% CI) \\")


def screening_rows():
    """Return the overall rate rows of all configurations, sorted by rate."""
    domain_cells = load_successful("domain")
    outcome_cells = load_successful("outcome")
    answered = {key[0] for key in domain_cells} | {key[0] for key in outcome_cells}
    pmids = sorted(final_sample_pmids() & answered)
    return sorted(all_configurations(outcome_cells, pmids), key=lambda row: row["rate"])


def table_line(row, mean_per_year):
    """Render one configuration as a LaTeX table row."""
    rate = f"{100 * row['rate']:.1f}\\% ({100 * row['low']:.0f}--{100 * row['high']:.0f})"
    papers = (f"{mean_per_year * row['rate']:,.0f} "
              f"({mean_per_year * row['low']:,.0f}--{mean_per_year * row['high']:,.0f})")
    prompt = row["prompt"].split("_")[0]
    counts = f"{row['yes']:,.0f}/{row['n']:,.0f}"
    return f"    {MODEL_LABELS[row['model']]} & {prompt} & {counts} & {rate} & {papers} \\\\"


def caption(per_year):
    """Build the table caption from the eligible-paper counts per year."""
    total, years = sum(per_year.values()), len(per_year)
    return ("\\caption{Percentage of papers in the screening sample presenting synergy as "
            "desirable (i.e.\\ answered `yes') for each configuration, and the resulting "
            "estimated number of eligible papers per year across all domains, both with 95\\% "
            "confidence intervals (normal approximation). Rates are scaled to the mean number "
            f"of eligible papers per year: {total:,} papers over {years} years (2010--2025), "
            f"i.e.\\ $\\bar{{N}}$ = {total / years:,.0f}.}}")


def build_table(rows, per_year):
    """Assemble the LaTeX table source."""
    mean_per_year = sum(per_year.values()) / len(per_year)
    body = "\n".join(table_line(row, mean_per_year) for row in rows)
    return "\n".join([GENERATED_NOTE, "\\begin{table}[h]", "  \\centering\\small",
                      f"  {caption(per_year)}", "  \\label{tab:rates}",
                      "  \\begin{tabular}{llrrr}", "    \\hline", f"    {COLUMN_HEADER}",
                      "    \\hline", body, "    \\hline", "  \\end{tabular}", "\\end{table}", ""])


def main():
    """Write the generated rate table into the supplementary folder."""
    TABLE_PATH.write_text(build_table(screening_rows(), gated_papers_per_year()))
    print(f"wrote {TABLE_PATH}")


if __name__ == "__main__":
    main()
